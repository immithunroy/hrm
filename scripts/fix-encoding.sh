#!/bin/bash
# Fix corrupted UTF-8 characters (em-dash and bullet)
find /root/zkt-app/frontend/src -name '*.tsx' -o -name '*.ts' | while read f; do
  if grep -qP '\xc3\xa2\xc2\x80' "$f" 2>/dev/null; then
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x94/\xe2\x80\x94/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x9c/\xe2\x80\x9c/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x9d/\xe2\x80\x9d/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\xa2/\xe2\x80\xa2/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\xa6/\xe2\x80\xa6/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x98/\xe2\x80\x98/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x99/\xe2\x80\x99/g' "$f"
    sed -i 's/\xc3\xa2\xc2\x80\xc2\x93/\xe2\x80\x93/g' "$f"
    echo "Fixed: $f"
  fi
done
